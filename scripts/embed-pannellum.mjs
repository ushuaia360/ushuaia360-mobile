/**
 * Genera `components/panorama-pannellum-inline.ts` desde `node_modules/pannellum`.
 * Ejecutar tras actualizar la dependencia: `node scripts/embed-pannellum.mjs`
 */
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const js = readFileSync(join(root, 'node_modules/pannellum/build/pannellum.js'), 'utf8');
const css = readFileSync(join(root, 'node_modules/pannellum/build/pannellum.css'), 'utf8');

const out = join(root, 'components/panorama-pannellum-inline.ts');
const body =
  `/** Auto-generated by scripts/embed-pannellum.mjs — do not edit */\n\n` +
  `export const PANNELLUM_INLINE_JS = ${JSON.stringify(js)};\n\n` +
  `export const PANNELLUM_INLINE_CSS = ${JSON.stringify(css)};\n`;

writeFileSync(out, body, 'utf8');
console.log(`Wrote ${out} (${(js.length + css.length) / 1024} KiB source)`);
